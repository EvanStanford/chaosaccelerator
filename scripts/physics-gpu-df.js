    "      if (dfLess(t, DF_ZERO)) { t = DF_ZERO; s = dfClamp(dfDiv(dfNeg(c), a), DF_ZERO, DF_ONE); }",
    "      else if (dfGreater(t, DF_ONE)) { t = DF_ONE; s = dfClamp(dfDiv(dfSub(b, c), a), DF_ZERO, DF_ONE); }",
    "    }",
    "  }",
    "  DClosestPair result;",
    "  result.c1 = dv2Add(p1, dv2Scale(d1, s));",
    "  result.c2 = dv2Add(p2, dv2Scale(d2, t));",
    "  return result;",
    "}",
    "",
