    "  if (!dfGreater(dfAbs(f0), R)) {",
    "    t = DF_ZERO;",
    "  } else {",
    "    MF target = dfGreater(f0, DF_ZERO) ? R : dfNeg(R);",
    "    if (!dfGreater(dfAbs(fv), DF_EPS9)) return dfNeg(DF_ONE);",
