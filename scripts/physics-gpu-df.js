    "  t = dfClamp(t, DF_ZERO, DF_ONE);",
    "  return dv2Add(g.e0, dv2Scale(g.seg, t));",
    "}",
    "",
    "DClosestPair dfClosestPointsSegmentSegment(DSegment g1, DSegment g2) {",
    "  DVec2 p1 = g1.e0, p2 = g2.e0;",
    "  DVec2 d1 = g1.seg;",
    "  DVec2 d2 = g2.seg;",
    "  DVec2 r = dv2Sub(p1, p2);",
    "  MF a = g1.lenSq, e = g2.lenSq, f = dv2Dot(d2, r);",
    "  MF s, t;",
    "  if (!dfGreater(a, DF_EPS9) && !dfGreater(e, DF_EPS9)) {",
    "    s = DF_ZERO; t = DF_ZERO;",
    "  } else if (!dfGreater(a, DF_EPS9)) {",
    "    s = DF_ZERO; t = dfClamp(dfDiv(f, e), DF_ZERO, DF_ONE);",
    "  } else {",
    "    MF c = dv2Dot(d1, r);",
    "    if (!dfGreater(e, DF_EPS9)) {",
    "      t = DF_ZERO; s = dfClamp(dfDiv(dfNeg(c), a), DF_ZERO, DF_ONE);",
    "    } else {",
    "      MF b = dv2Dot(d1, d2);",
    "      MF denom = dfSub(dfMul(a, e), dfSqr(b));",
    "      s = !dfIsZero(denom) ? dfClamp(dfDiv(dfSub(dfMul(b, f), dfMul(c, e)), denom), DF_ZERO, DF_ONE) : DF_ZERO;",
    "      t = dfDiv(dfAdd(dfMul(b, s), f), e);",
    "      if (dfLess(t, DF_ZERO)) { t = DF_ZERO; s = dfClamp(dfDiv(dfNeg(c), a), DF_ZERO, DF_ONE); }",
    "      else if (dfGreater(t, DF_ONE)) { t = DF_ONE; s = dfClamp(dfDiv(dfSub(b, c), a), DF_ZERO, DF_ONE); }",
    "    }",
    "  }",
    "  DClosestPair result;",
    "  result.c1 = dv2Add(p1, dv2Scale(d1, s));",
    "  result.c2 = dv2Add(p2, dv2Scale(d2, t));",
    "  return result;",
