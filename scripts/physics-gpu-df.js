    "  MF disc = dfSub(dfSqr(qb), dfMulPow2(dfMul(qa, qc), 4.0));",
    "  if (dfLess(disc, DF_ZERO)) return dfNeg(DF_ONE);",
    "  MF t = dfDiv(dfSub(dfNeg(qb), dfSqrt(disc)), dfMulPow2(qa, 2.0));",
    "  if (dfLess(t, DF_ZERO) || dfGreater(t, dt)) return dfNeg(DF_ONE);",
    "  return t;",
    "}",
    "",
    "MF dfSweepPointSlab(DVec2 p, DVec2 v, DVec2 e0, DVec2 dir, MF len, MF R, MF dt) {",
