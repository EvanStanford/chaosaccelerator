    "  MF f = dfFirstRoot(neg ? dfNeg(a) : a, neg ? dfNeg(b) : b, c);",
    "  if (dfLess(f, DF_ZERO)) return f;",
    "  DVec2 Df = dv2Add(D, dv2Scale(mD, f));",
    "  MF s = dv2Dot(dv2Add(P, dv2Scale(mP, f)), Df);",
    "  return !dfLess(s, DF_ZERO) && !dfGreater(s, dv2LengthSq(Df)) ? f : dfNeg(DF_ONE);",
    "}",
    "MF dfFarPointNewton(DVec2 c, DVec2 q0, DVec2 dq0, DVec2 q1, DVec2 dq1, MF R, bool neg, MF f) {",
