    "}",
    "MF dfFirstRoot(MF a, MF b, MF c) {",
    "  MF f;",
    "  if (dfIsZero(a)) {",
    "    if (!dfLess(b, DF_ZERO)) return dfNeg(DF_ONE);",
    "    f = dfDiv(dfNeg(c), b);",
    "  } else {",
    "    MF disc = dfSub(dfSqr(b), dfMulPow2(dfMul(a, c), 4.0));",
    "    if (dfLess(disc, DF_ZERO)) return dfNeg(DF_ONE);",
    "    MF sq = dfSqrt(disc);",
    "    MF q = dfMulPow2(dfLess(b, DF_ZERO) ? dfSub(b, sq) : dfAdd(b, sq), -0.5);",
    "    if (dfIsZero(q)) return dfNeg(DF_ONE);",
    "    MF r1 = dfDiv(q, a), r2 = dfDiv(c, q);",
    "    f = dfMin(r1, r2);",
    "    if (dfLess(f, DF_ZERO)) f = dfMax(r1, r2);",
    "  }",
    "  return !dfLess(f, DF_ZERO) && !dfGreater(f, DF_ONE) ? f : dfNeg(DF_ONE);",
    "}",
    "MF dfSweepPointMovingSlab(DVec2 p, DVec2 dp, DVec2 q0, DVec2 dq0, DVec2 q1, DVec2 dq1, MF len, MF R) {",
    "  DVec2 D = dv2Sub(q1, q0), mD = dv2Sub(dq1, dq0), P = dv2Sub(p, q0), mP = dv2Sub(dp, dq0);",
    "  MF c0 = dv2Cross(D, P);",
    "  bool neg = dfLess(c0, DF_ZERO);",
    "  MF c = dfSub(neg ? dfNeg(c0) : c0, dfMul(R, len));",
    "  if (!dfGreater(c, DF_ZERO)) return dfNeg(DF_ONE);",
