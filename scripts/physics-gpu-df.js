    "DSegment dfLineSegment(DBody line, MF halfLen) {",
    "  DVec2 e0, e1;",
    "  dfLineEndpoints(line, halfLen, e0, e1);",
    "  return dfSegment(e0, e1);",
    "}",
    "",
    "DVec2 dfClosestPointOnSegment(DSegment g, DVec2 point) {",
    "  MF t = dfGreater(g.lenSq, DF_EPS12) ? dfDiv(dv2Dot(dv2Sub(point, g.e0), g.seg), g.lenSq) : DF_ZERO;",
    "  t = dfClamp(t, DF_ZERO, DF_ONE);",
    "  return dv2Add(g.e0, dv2Scale(g.seg, t));",
    "}",
    "",
    "DClosestPair dfClosestPointsSegmentSegment(DSegment g1, DSegment g2) {",
    "  DVec2 p1 = g1.e0, p2 = g2.e0;",
    "  DVec2 d1 = g1.seg;",
    "  DVec2 d2 = g2.seg;",
    "  DVec2 r = dv2Sub(p1, p2);",
    "  MF a = g1.lenSq, e = g2.lenSq, f = dv2Dot(d2, r);",
    "  MF s, t;",
    "  if (!dfGreater(a, DF_EPS9) && !dfGreater(e, DF_EPS9)) {",
    "    s = DF_ZERO; t = DF_ZERO;",
    "  } else if (!dfGreater(a, DF_EPS9)) {",
    "    s = DF_ZERO; t = dfClamp(dfDiv(f, e), DF_ZERO, DF_ONE);",
    "  } else {",
    "    MF c = dv2Dot(d1, r);",
    "    if (!dfGreater(e, DF_EPS9)) {",
    "      t = DF_ZERO; s = dfClamp(dfDiv(dfNeg(c), a), DF_ZERO, DF_ONE);",
    "    } else {",
    "      MF b = dv2Dot(d1, d2);",
    "      MF denom = dfSub(dfMul(a, e), dfSqr(b));",
