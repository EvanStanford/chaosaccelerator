    "}",
    "// The far-point slab's refinement of a moving slab's hit f (>= 0): two Newton steps, then its checks.",
    "MF dfFarPointRefine(DVec2 c, DVec2 q0, DVec2 dq0, DVec2 q1, DVec2 dq1, MF R, MF f) {",
