    "  DVec2 dvec = dv2Sub(p, c);",
    "  MF qc = dfSub(dv2LengthSq(dvec), dfSqr(R));",
    "  if (!dfGreater(qc, DF_ZERO)) return DF_ZERO;",
    "  MF qa = dv2LengthSq(v);",
    "  if (!dfGreater(qa, DF_EPS9)) return dfNeg(DF_ONE);",
