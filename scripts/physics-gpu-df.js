    "  if (dfLess(s, DF_ZERO) || dfGreater(s, len)) return dfNeg(DF_ONE);",
    "  return t;",
    "}",
    "",
    "// ---- Swept line contacts: the ports of physics-gpu.js's, f the fraction of the step ----",
    "// The bounding checks in float32 about A's center, a pixel wide.",
    "bool dfLinesMayTouch(DBody a, DSegment gA, MF halfA, DBody b, DSegment gB, MF halfB) {",
    "  DVec2 ca = dv2(a.x, a.y);",
    "  vec2 d = dv2ToVec2(dv2Sub(dv2(b.x, b.y), ca));",
    "  vec2 m = dv2ToVec2(dv2Sub(dv2(b.vx, b.vy), dv2(a.vx, a.vy))) * DT;",
