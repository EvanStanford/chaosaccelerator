    "  MF disc = dfSub(dfSqr(qb), dfMulPow2(dfMul(qa, qc), 4.0));",
    "  if (dfLess(disc, DF_ZERO)) return dfNeg(DF_ONE);",
    "  MF t = dfDiv(dfSub(dfNeg(qb), dfSqrt(disc)), dfMulPow2(qa, 2.0));",
    "  if (dfLess(t, DF_ZERO) || dfGreater(t, dt)) return dfNeg(DF_ONE);",
    "  return t;",
    "}",
    "",
    "MF dfSweepPointSlab(DVec2 p, DVec2 v, DVec2 e0, DVec2 dir, MF len, MF R, MF dt) {",
    "  DVec2 perp = dv2Perp(dir);",
    "  MF f0 = dv2Dot(dv2Sub(p, e0), perp);",
    "  MF fv = dv2Dot(v, perp);",
    "  MF t;",
    "  if (!dfGreater(dfAbs(f0), R)) {",
    "    t = DF_ZERO;",
    "  } else {",
    "    MF target = dfGreater(f0, DF_ZERO) ? R : dfNeg(R);",
    "    if (!dfGreater(dfAbs(fv), DF_EPS9)) return dfNeg(DF_ONE);",
    "    t = dfDiv(dfSub(target, f0), fv);",
    "    if (dfLess(t, DF_ZERO) || dfGreater(t, dt)) return dfNeg(DF_ONE);",
    "  }",
    "  MF s = dv2Dot(dv2Sub(dv2Add(p, dv2Scale(v, t)), e0), dir);",
    "  if (dfLess(s, DF_ZERO) || dfGreater(s, len)) return dfNeg(DF_ONE);",
    "  return t;",
    "}",
    "",
    "// ---- Swept line contacts: the ports of physics-gpu.js's, f the fraction of the step ----",
    "// The bounding checks in float32 about A's center, a pixel wide; aroundB: B is a port hole turning A round it.",
    "bool dfLinesMayTouch(DBody a, DSegment gA, MF halfA, DBody b, DSegment gB, MF halfB, MF reachB, bool aroundB) {",
    "  DVec2 ca = dv2(a.x, a.y);",
    "  vec2 d = dv2ToVec2(dv2Sub(dv2(b.x, b.y), ca));",
